import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const shots = 'artifacts/screenshots';
test.beforeEach(async ({ page }) => {
  await mkdir(shots, { recursive: true });
  await page.goto('/');
  await page.getByRole('button', { name: 'Load demo', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'What matters to you?' })).toBeVisible();
  await expect(page.locator('[data-nextjs-dialog]')).toHaveCount(0);
});
async function analyze(page: import('@playwright/test').Page, path: string) {
  await page.getByRole('button', { name: 'Demo controls' }).click();
  await page.getByLabel('Try a path').selectOption(path);
  await page.getByRole('button', { name: 'Interpret my needs' }).click();
  await expect(page.getByRole('heading', { name: 'Your buying criteria' })).toBeVisible();
  await page.getByRole('button', { name: 'Confirm & analyze reviews' }).click();
  await expect(page.getByRole('heading', { name: 'Evidence, in your context.' })).toBeVisible();
}
test('A: comfort conflict → investigate → brief → source review; reload restores', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.screenshot({ path: `${shots}/criteria.png`, fullPage: true });
  await analyze(page, 'conflict');
  await expect(page.getByRole('button', { name: 'Read decision brief' })).toBeVisible();
  await expect(page.getByText('Context difference found')).toBeVisible();
  await page.screenshot({ path: `${shots}/workspace.png`, fullPage: true });
  await page.getByRole('button', { name: 'Read decision brief' }).click();
  await expect(page.getByRole('heading', { name: 'Before you buy' })).toBeVisible();
  await page.screenshot({ path: `${shots}/brief.png`, fullPage: true });
  await page.getByRole('button', { name: 'R5' }).first().click();
  await expect(page.getByRole('dialog')).toContainText('Wearing glasses');
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.reload(); await page.getByRole('button', { name: '3 Decision brief' }).click();
  await expect(page.getByText('Complete with caveats', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
